export const STRINGS = {es, en, it, pt, fr};

export function resolveLang(pref, systemLang) {
  if (pref !== 'auto' && STRINGS[pref]) return pref;
  return STRINGS[systemLang] ? systemLang : 'en';
}

export const langName = code => (LANGUAGES.find(l => l.code === code) || LANGUAGES[1]).name;

export const fmt = (s, vars) => s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k]));
